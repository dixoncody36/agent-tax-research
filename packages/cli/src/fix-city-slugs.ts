import { desc, eq, inArray } from "drizzle-orm";
import {
  client, db, jurisdictions, proposalItems, proposals, sources, sourceSnapshots, taxRates, taxTypes,
} from "@agent-tax-research/database";
import { assignSlugs, isValidCitySlug, parseCityRows } from "./city-slug.js";

// One-time #35 cleanup: re-derive city registrations from the stored
// Comptroller snapshot with the fixed parser. Safety rails: aborts if any
// affected jurisdiction carries published tax_rates, or if the old city
// proposal is already approved/published. The verified old proposal is
// rejected as superseded (verified items are never edited); a corrected
// proposal is filed as `proposed` for a fresh distinct Reviewer pass.
// Structure rows only — nothing here publishes a tax fact.
const OLD_PROPOSAL = "485ff772-a03f-4888-86ce-27895549783d";

const [src] = await db.select().from(sources)
  .where(eq(sources.url, "https://comptroller.texas.gov/taxes/sales/city.php")).limit(1);
if (!src) throw new Error("city source missing");
const [snap] = await db.select().from(sourceSnapshots)
  .where(eq(sourceSnapshots.sourceId, src.id)).orderBy(desc(sourceSnapshots.createdAt)).limit(1);
if (!snap?.retrievedText) throw new Error("city snapshot text missing");

const { rows, rejected } = parseCityRows(snap.retrievedText);
const slugByCode = assignSlugs(rows);
const expectedCodes = new Set(rows.map((r) => r.code));
console.log(`snapshot parse: accepted=${rows.length} rejected=${rejected.length}`);
for (const r of rejected) console.log(`  rejected ${r.code} "${r.name}" (${r.reason})`);

const [oldProp] = await db.select().from(proposals).where(eq(proposals.id, OLD_PROPOSAL)).limit(1);
if (!oldProp) throw new Error("old city proposal missing");
if (oldProp.status !== "verified") throw new Error(`old proposal status=${oldProp.status}; expected verified — aborting`);

const cities = await db.select().from(jurisdictions).where(eq(jurisdictions.level, "city"));
const coded = cities.filter((c) => typeof c.datavalues?.comptrollerLocalCode === "string");
const byCode = new Map(coded.map((c) => [String(c.datavalues.comptrollerLocalCode), c]));

// Refuse to touch anything with published facts hanging off it.
const cityIds = coded.map((c) => c.id);
const published = cityIds.length
  ? await db.select({ id: taxRates.id }).from(taxRates).where(inArray(taxRates.jurisdictionId, cityIds)).limit(1)
  : [];
if (published.length) throw new Error("published tax_rates reference bulk cities — aborting");

let kept = 0, renamed = 0, deleted = 0, inserted = 0;
const [tx] = await db.select().from(jurisdictions).where(eq(jurisdictions.slug, "us-tx")).limit(1);
if (!tx) throw new Error("us-tx missing");

// Delete structure rows whose code the fixed parser rejects (non-cities,
// fragments). Austin (seeded, uncoded datavalues) is never in `coded`.
for (const c of coded) {
  const code = String(c.datavalues.comptrollerLocalCode);
  if (!expectedCodes.has(code)) {
    await db.delete(jurisdictions).where(eq(jurisdictions.id, c.id));
    console.log(`  delete ${c.slug} (code ${code})`);
    deleted += 1;
  }
}
// Rename survivors to their canonical slug/name; stamp the official code.
for (const r of rows) {
  const want = slugByCode.get(r.code)!;
  const existing = byCode.get(r.code);
  if (existing && expectedCodes.has(r.code)) {
    if (existing.slug !== want || existing.name !== r.name || existing.code !== r.code) {
      await db.update(jurisdictions)
        .set({ slug: want, name: r.name, code: r.code, updatedAt: new Date() })
        .where(eq(jurisdictions.id, existing.id));
      console.log(`  rename ${existing.slug} -> ${want}`);
      renamed += 1;
    } else kept += 1;
  } else if (!existing) {
    const [slugHit] = await db.select({ id: jurisdictions.id }).from(jurisdictions)
      .where(eq(jurisdictions.slug, want)).limit(1);
    if (slugHit) { kept += 1; continue; } // seeded Austin row (code 2227016)
    await db.insert(jurisdictions).values({
      slug: want, parentId: tx.id, level: "city", code: r.code, name: r.name, countryCode: "US",
      datavalues: { comptrollerLocalCode: r.code, combinedTotalShown: r.total },
    });
    console.log(`  insert ${want} (code ${r.code})`);
    inserted += 1;
  }
}

// Supersede the verified proposal; file the corrected one for re-review.
await db.update(proposals).set({
  status: "rejected",
  datavalues: { ...oldProp.datavalues, supersededReason: "#35 malformed slugs/non-city rows; regenerated by fix-city-slugs.ts" },
  updatedAt: new Date(),
}).where(eq(proposals.id, OLD_PROPOSAL));

const [salesType] = await db.select().from(taxTypes).where(eq(taxTypes.slug, "us-tx-sales-use")).limit(1);
if (!salesType) throw new Error("sales type missing");
const [prop] = await db.insert(proposals).values({
  jurisdictionId: tx.id, taxTypeId: salesType.id, status: "proposed",
  datavalues: { regeneratedFor: "#35", supersedes: OLD_PROPOSAL },
}).returning({ id: proposals.id });
let items = 0;
for (const r of rows) {
  const slug = slugByCode.get(r.code)!;
  if (!isValidCitySlug(slug)) throw new Error(`invalid slug generated: ${slug}`);
  await db.insert(proposalItems).values({
    proposalId: prop!.id, targetTable: "tax_rates",
    payload: { rateValue: r.rate, rateUnit: "percent", jurisdictionSlug: slug, appliesTo: `City sales/use tax component (${r.name}, Comptroller local code ${r.code}); table combined total shown ${r.total}%` },
    citation: "Texas Comptroller City Sales and Use Tax Rates table snapshot",
    sourceId: src.id, snapshotId: snap.id, verdict: "pending",
  });
  items += 1;
}
console.log(`kept=${kept} renamed=${renamed} deleted=${deleted} inserted=${inserted} newProposal=${prop!.id} items=${items}`);
await client.end();
